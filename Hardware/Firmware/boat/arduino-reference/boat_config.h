/**
 * 智护库安 —— 硬件地址配置（单一数据源）
 *
 * 两个 .ino 都包含本文件，避免 MAC 散落两处、改一处漏一处导致 ESP-NOW 不通。
 * 换硬件时只改这里。
 *
 * ============================ 对端 MAC 的正确含义 ============================
 * ESP-NOW 使用的是 **Wi-Fi STA 接口的 MAC**，即固件里
 * `WiFi.macAddress()` 的返回值，不是蓝牙 MAC，也不一定是 eFuse 基址。
 *
 * ESP32 / ESP32-S3 的 Wi-Fi STA MAC 与 eFuse 基址的关系（实测确认）：
 *
 *     芯片         eFuse 基址 (esptool read-mac)     Wi-Fi STA / ESP-NOW
 *     ESP32-S3     a0:f2:62:e3:94:dc                 a0:f2:62:e3:94:dc   ← 相同
 *     ESP32-C3     10:b4:1d:24:a6:1c                 10:b4:1d:24:a6:1c   ← 相同
 *
 * 所以可以用 `esptool.py --chip <chip> read-mac` 直接查到要填的值，
 * 不必烧写诊断固件。若日后换用 4-MAC 批次的模组，STA 可能变成基址 +4，
 * 此时务必用 controller.ino 启动日志里打印的 MAC 复核。
 * ===========================================================================
 */

