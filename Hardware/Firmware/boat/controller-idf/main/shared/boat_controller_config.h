#pragma once

/* 目录关系： main/shared/ -> main/ -> controller-idf/ -> boat/ -> arduino-reference/ */
#include "../../../arduino-reference/boat_config.h"

/* ---------------------------------------------------------------------------
 * 电机方向取反
 *
 * 两个明轮是左右镜像安装的，所以其中一个电机的"正转"在电气上要取反。
 * Arduino 参考实现里写死了 M1_DIRECTION_INVERTED = true（manifest 见
 * arduino-reference/main/main.ino），ESP-IDF 移植时漏掉了这一句，导致同样的
 * 符号在参考固件和本固件下会朝相反方向转。
 *
 * 默认按参考实现取反。**首次下水前必须抬轮验证**：
 *   - 推 W，两轮应同时向前；若某侧反转，把对应宏改成 0
 *   - 按 A，船应向左转；若右转，先看 dashboard 的 steer 符号（已按
 *     "正 steer = 右转" 统一），再确认电机接线
 * ------------------------------------------------------------------------- */
#define M1_DIRECTION_INVERTED 1
#define M2_DIRECTION_INVERTED 0

/* ---------------------------------------------------------------------------
 * 安全开关：电机输出
 *   1 = 正常输出（与 Arduino 版默认一致）
 *   0 = 电机强制不转，用于陆地调试
 *
 * 陆地调试建议改成 0 重新编译 —— 比拔线更可靠，因为固件层就断掉了输出，
 * 即使误发指令也不会转。
 * ------------------------------------------------------------------------- */
#define ENABLE_MOTOR_OUTPUT   1

/* ---------------------------------------------------------------------------
 * HUSKYLENS 2 通信方式：0 = I2C（与现有接线一致），1 = UART
 *
 * 默认 I2C：DFR1063 的 GPIO8=SDA / GPIO9=SCL，二哈的绿线接 SDA、蓝线接 SCL，
 * 且二哈的"Protocol Type"需设为 I2C。保持与原来 Arduino 版一致，不用改接线。
 * ------------------------------------------------------------------------- */
#define HUSKYLENS_USE_UART   0

/* I2C 引脚与速率 */
#define HUSKY_I2C_SDA_GPIO   8
#define HUSKY_I2C_SCL_GPIO   9
#define HUSKY_I2C_FREQ_HZ    100000
#define HUSKY_I2C_ADDR       0x50

/* UART 备用引脚（仅当 HUSKYLENS_USE_UART=1 时生效） */
#define HUSKY_UART_PORT      1
#define HUSKY_UART_TX_GPIO   1
#define HUSKY_UART_RX_GPIO   2
#define HUSKY_UART_BAUD      115200

/* ---------------------------------------------------------------------------
 * HUSKYLENS 2 使用的算法 ID
 *
 * 默认 3 = 内置"物体追踪"（OBJECT_TRACKING，协议文档"算法 ID"表里的 1~19 之一）。
 *
 * **装了自训练模型后可以填 0 让它自动探测，也可以填设备上显示的 ID。**
 * 二哈识图 2 支持部署自训练模型；按官方协议，**算法 ID 128~255 专门留给用户安装的模型**，
 * 所以：
 *
 *   0    = 开机自动扫描 128~255，找到第一个可用的用户模型 ID（找不到回退 3）。
 *          首次启动会多花几秒；日志会打印 "发现用户模型算法 ID=xx"，
 *          建议把探测到的值写死到本宏，之后开机就快了。
 *   3    = 内置物体追踪（没装自定义模型时）。
 *   1~19 = 其他内置算法。
 *   128~255 = 直接指定自定义模型 ID。
 *
 * 怎么手动读 ID（不想用自动探测时）：
 *   1. 二哈上电，进入那个"自定义模型"功能页；
 *   2. 看该功能页左上角（或"信息/i"页）显示的算法 ID 序号；
 *   3. 把下面的宏改成该数字，重新编译烧录即可，不需要动任何解析代码。
 *
 * 取值必须是 0~255（协议帧的 AlgoID 只有一个字节，main.c 有编译期断言兜底）。
 * 启动日志会打印实际使用的 ID（自动探测时还会打印配置值和探测结果），便于现场核对。
 * ------------------------------------------------------------------------- */
#define HUSKY_ALGORITHM_ID   3
