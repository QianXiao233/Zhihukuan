/* 16x16 汉字点阵结构 */
typedef struct {
    unsigned char index[2];   /* GB2312 编码高/低字节 */
    unsigned char data[32];   /* PCtoLCD 格式：前16字节上半部，后16字节下半部 */
} CH_CN16;

/* LCD 显示汉字（16x16） */
void LCD_ShowChinese(u16 x, u16 y, const unsigned char *str, u16 color)
{
    u16 old_color = POINT_COLOR;
    POINT_COLOR = color;

    while (*str)
    {
        /* 查找汉字 */
        extern const CH_CN16 chinese_16[];
        const CH_CN16 *p = chinese_16;
        int found = 0;

        while (p->index[0] || p->index[1])
        {
            if (p->index[0] == str[0] && p->index[1] == str[1])
            {
                int i, j;
                for (i = 0; i < 16; i++)
                {
                    /* PCtoLCD 格式：前16字节上半部，后16字节下半部 */
                    for (j = 0; j < 8; j++)
                    {
                        if (p->data[i] & (0x80 >> j))
                            LCD_Fast_DrawPoint(x + i, y + j, POINT_COLOR);
                        else
                            LCD_Fast_DrawPoint(x + i, y + j, BACK_COLOR);
                    }
                    for (j = 0; j < 8; j++)
                    {
                        if (p->data[16 + i] & (0x80 >> j))
                            LCD_Fast_DrawPoint(x + i, y + 8 + j, POINT_COLOR);
                        else
                            LCD_Fast_DrawPoint(x + i, y + 8 + j, BACK_COLOR);
                    }
                }
                found = 1;
                break;
            }
            p++;
        }
        str += 2;
        x += 16;
        (void)found;
    }
    POINT_COLOR = old_color;
}

